@pytest.mark.parametrize("restart", [False, True], ids=["saved_v6_resume", "saved_v6_new_manager_resume"])
def test_actual_saved_v6_checkpoint_binding_load_and_replay_ignore_new_v7_default(tmp_path, monkeypatch, restart):
    from tests.test_semantic_review_model_integration import setup, immutable
