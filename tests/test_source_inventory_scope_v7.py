@pytest.mark.parametrize("entry", VECTORS, ids=lambda row: f"{row['policy'] or 'absent'}_{'off' if row['image_off'] else 'on'}")
def test_all_prechange_full_requests_descriptors_bindings_and_fingerprints_remain_exact(tmp_path, entry):
    assert sha(GOLDEN.read_bytes()) == "4b5e5a247919871e00a18f73139466ae1f9493d06fd7f4738f626a4d599c7166"
    client = Client()
    selected, off = entry["policy"], entry["image_off"]
    run(tmp_path / "audit", selected, client, off=off)
    assert [sha(review.audit._json(request)) for request in client.requests] == entry["request_sha256"]
    assert [sha(review.audit._json(request["response_format"])) for request in client.requests] == entry["schema_sha256"]
    assert (policy.descriptor(selected) if selected is not None else None) == entry["descriptor"]
    binding = json.loads((tmp_path / "audit/manifest.json").read_bytes())["binding"]
    assert sha(review.audit._json(binding)) == entry["binding_sha256"]
    assert review.semantic_review_source_fingerprint(pack(count=2, off=off),
        recipe(configured_image_mode="off" if off else "auto"), PDF, **OPTIONS, **{KEY: selected}) == entry["source_fingerprint"]


def test_only_inventory_instructions_advance_but_all_new_request_descriptors_change(tmp_path):
    assert policy.POLICY_V7 == V7
    assert sha(policy.V7_INVENTORY_SCOPE) == "e5ee74670b6457575ea94f15f67ae6e8b97df89ff1bad4610638e361601d0d6a"
    before, after = policy._suffixes(policy.POLICY_V6), policy._suffixes(V7)
    assert after == {**before, "source_inventory": before["source_inventory"] + policy.V7_INVENTORY_SCOPE}
    old, new = Client(), Client()
    first = run(tmp_path / "v6", policy.POLICY_V6, old)
    second = run(tmp_path / "v7", V7, new)
    assert first.selected_text_by_page == second.selected_text_by_page
    for stage, left, right in zip(review.STAGES, old.requests, new.requests):
        assert sha(review.audit._json(left)) != sha(review.audit._json(right))
        a, b = json.loads(left["prompt_text"]), json.loads(right["prompt_text"])
        assert a.pop(KEY) == policy.descriptor(policy.POLICY_V6)
        assert b.pop(KEY) == policy.descriptor(V7)
        assert a == b
        assert right["instructions"] == left["instructions"] + (policy.V7_INVENTORY_SCOPE if stage == "source_inventory" else "")
        assert {k: v for k, v in left.items() if k not in {"instructions", "prompt_text"}} == {
            k: v for k, v in right.items() if k not in {"instructions", "prompt_text"}}


