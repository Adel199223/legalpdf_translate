@pytest.mark.parametrize("failure", ["source_unresolved", "missing", "contradiction", "unsupported", "unresolved"])
def test_other_strict_failures_remain_fatal_under_v7(tmp_path, failure):
    def damage(stage, data, payload):
        if stage == "source_inventory" and failure == "source_unresolved": data["claims"][0]["unresolved"] = True
        if stage == "verification":
            if failure in {"missing", "contradiction", "unresolved"}: data["claim_results"][0]["status"] = failure
            if failure == "unsupported": data["unsupported_additions"] = [{"target_unit_ids": [payload["target_units"][0]["unit_id"]], "reason": "Fictional unsupported addition."}]
        return data
    with pytest.raises(review.SemanticAuditError):
        run(tmp_path / "audit", V7, Client(damage))
    assert not (tmp_path / "audit/manifest.json").exists()


